export const balKey = (a, b) => `${String(a).trim()}|${String(b).trim()}`;
const BY_KEY = new Map(BALANCE.map(x => [balKey(x[1], x[2]), x]));

/* ----- 날짜 ----- */
const dayNo = ymd => Math.floor(Date.UTC(+ymd.slice(0, 4), +ymd.slice(4, 6) - 1, +ymd.slice(6, 8)) / 86400e3);
const ymdOfNo = n => new Date(n * 86400e3).toISOString().slice(0, 10).replace(/-/g, '');
const dowOf = ymd => new Date(dayNo(ymd) * 86400e3).getUTCDay();
export const NEW_FROM = '20261027';   // 이 날 문제부터 일요일 포함 · 밤 11시 마감 (2026-10-26까지는 예전 규칙 그대로)
// 밸런스 게임이 열리는 날: 예전엔 월~금, NEW_FROM부터 토요일만 쉼
export const isBalDay = ymd => ymd >= NEW_FROM ? dowOf(ymd) !== 6 : dowOf(ymd) % 6 !== 0;

/* ----- 그날 질문 고르기 (한 번 나온 질문은 다시 안 나옴) ----- */
async function usedKeys(db) {
  const r = await db.prepare("SELECT k FROM balance_auto UNION SELECT a || '|' || b FROM balance_custom").all();
  return new Set(r.results.map(x => x.k));
}
// 'YYYYMMDD' → [질문, A, B] · 쓸 질문이 다 떨어지면 null (같은 질문을 다시 내지 않음 — 관리자 화면에 남은 개수 경고)
export async function balanceOf(db, ymd) {
  const c = await db.prepare('SELECT q, a, b FROM balance_custom WHERE ymd = ?1').bind(ymd).first();
  if (c) return [c.q, c.a, c.b];
  for (let i = 0; i < 4; i++) {
    const got = await db.prepare('SELECT q, a, b FROM balance_auto WHERE ymd = ?1').bind(ymd).first();
    if (got) return [got.q, got.a, got.b];
    const used = await usedKeys(db), next = BALANCE.find(x => !used.has(balKey(x[1], x[2])));
    if (!next) return null;
    // ymd·k 둘 다 UNIQUE → 동시에 고르는 워커가 있어도 한 날짜엔 한 질문, 한 질문은 한 날짜만
    await db.prepare('INSERT OR IGNORE INTO balance_auto (ymd, k, q, a, b, at) VALUES (?1, ?2, ?3, ?4, ?5, ?6)')
      .bind(ymd, balKey(next[1], next[2]), next[0], next[1], next[2], Date.now()).run();
  }
  return null;
}
// 관리자 미리보기: 앞으로의 밸런스 날짜에 나올 질문(아직 안 정해진 날은 순서대로 예상) + 남은 기본 질문 수
export async function previewBalance(db, days) {
  const [cus, auto] = await db.batch([
    db.prepare('SELECT ymd, q, a, b FROM balance_custom'),
    db.prepare('SELECT ymd, k, q, a, b FROM balance_auto'),
  ]);
  const cMap = new Map(cus.results.map(x => [x.ymd, x])), aMap = new Map(auto.results.map(x => [x.ymd, x]));
  const used = new Set([...auto.results.map(x => x.k), ...cus.results.map(x => balKey(x.a, x.b))]);
  const left = BALANCE.filter(x => !used.has(balKey(x[1], x[2])));
  let p = 0;
  const out = days.map(ymd => {
    const c = cMap.get(ymd) || aMap.get(ymd);
    if (c) return { ymd, custom: cMap.has(ymd), q: c.q, a: c.a, b: c.b };
    const n = left[p++];
    return n ? { ymd, custom: false, q: n[0], a: n[1], b: n[2] } : { ymd, custom: false, q: '(남은 기본 질문 없음 — 직접 지정해 주세요)', a: '', b: '' };
  });
  return { days: out, left: left.length };
}
