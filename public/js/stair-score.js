// '영상고 계단 오르기' 규칙 — 화면(stair.js)과 서버(functions/api/s)가 같이 쓴다. 바꾸면 이미 쌓인 기록과 비교가 안 맞으니 신중히.
// 랭킹은 다른 게임처럼 '작을수록 1등' 구조라 서버엔 STAIR_MAX - 오른 계단 수로 저장한다(집에 가고 싶어!·기자재 정리!와 같은 방식).
export const STAIR_MAX = 9999999;
export const GAIN = 0.075;          // 한 칸 오를 때 차는 종 게이지(전체 = 1)
export const FLOOR = 100;           // 100칸마다 한 층(2026-10-28 하율: 엘리베이터 없는 영상고 — 한 층 오르기가 힘들게)
export const MIN_STEP_MS = 55;      // 사람이 한 칸 오르는 데 걸리는 최소 시간(1초에 18칸 넘게는 못 누름) — 서버 검사용
// 종 게이지가 1초에 줄어드는 양(2026-10-28 하율 "700칸(옥상)까지는 갈 수 있게 + 판은 끝나게" — 시뮬레이션 후 결정):
//   0~700칸: 0.13 → 0.55로 천천히(1초 1.7칸 → 7.3칸 필요) · 700칸 이후: 아주 조금씩 계속(1,000칸쯤 1초 약 8칸) · 약 3,590칸부터 0.9(1초 12칸)로 고정
//   예전(350칸에서 0.55로 고정)은 700칸 가는 학생이 10명 중 1~2명, 손 빠른 사람은 판이 끝나지 않았음(최장 20분+) → 지금 곡선: 2~3명, 최장 약 6분
export const drain = steps => 0.13 + Math.min(0.42, steps * 0.0006) + Math.min(Math.max(steps - 700, 0) * (0.20 / 1650), 0.35);
// 서버 검사용: steps칸을 오르며 버틸 수 있는 가장 긴 시간(ms). 게이지는 처음 1 + 칸마다 GAIN만 차고, 아무리 느려도 1초에 0.13씩은 줄어듦
export const maxMs = steps => Math.ceil((1 + steps * GAIN) / 0.13 * 1000) + 2000;
// 층 이름: 학교 1~7층 → 옥상(700칸, 2026-10-28 하율 "옥상은 7층까지 높여") → 그 위는 높이(m, 100칸마다 100m) — 하늘(100~200m) · 구름 위(300~400m) · 우주(500m~)
export const ROOF = 7;
export const zoneOf = f => f < ROOF ? '학교' : f === ROOF ? '옥상' : f < ROOF + 3 ? '하늘' : f < ROOF + 5 ? '구름 위' : '우주';
export const floorName = (f, short = false) => f <= 0 ? '1층' : f < ROOF ? (f + 1) + '층' : f === ROOF ? '옥상' : (short ? '' : zoneOf(f) + ' ') + (f - ROOF) * 100 + 'm';
